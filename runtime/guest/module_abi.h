#pragma once
// The boundary between TenchuZ.exe (the runtime, no game code) and tenchu_game.dll (the
// code translated from the player's default.xex, built by tools/recompile.py and
// tools/make_module.ps1), modeled on the NFL Blitz 2003 port's game module.
//
// The DLL exports one C function, tenchu_module_init. The runtime passes the services the
// generated code calls (RuntimeApi) and gets back the module's tables (GameModule). Host
// functions the module calls (kernel/XAM imports, overrides of game functions, mid-asm
// hooks) are bound by name: the module lists the names it needs and the runtime fills
// its slots from the functions registered with runtime/guest/host.h before any guest code
// runs. The runtime reaches guest code only by guest address, through the function table.
//
// Bump kModuleAbiVersion whenever PPCContext, ppc_config.h, RuntimeApi or GameModule change.
// Include the PPC context header (ppc_context.h or ppc_context.template.h) first.
#include <cstdint>

namespace tz {

inline constexpr uint32_t kModuleAbiVersion = 1;

struct RuntimeApi {
    uint32_t abiVersion;
    uint32_t contextSize;  // sizeof(PPCContext)
    void (*recompFailure)(const PPCContext& ctx, uint32_t address, const char* reason);
    uint64_t (*queryTimebase)();
    uint32_t (*mmioRead32)(uint32_t address);
    void (*mmioWrite32)(uint32_t address, uint32_t value);
};

// Kernel variables the executable imports by address (filled in by the runtime).
struct DataImport {
    uint32_t slot;
    const char* name;
};

struct GameModule {
    uint32_t abiVersion;
    uint32_t contextSize;
    uint64_t imageBase, imageSize, codeBase, codeSize;  // ppc_config.h of the generator
    const PPCFuncMapping* functions;                    // {guest, host}, ends with {0, nullptr}
    uint32_t functionCount;
    uint32_t entryPoint;
    // Host functions the module calls: "__imp__<Import>", "sub_<address>" (overrides) and
    // "<Hook>/<register count>" (mid-asm hooks). The runtime stores each one in hostSlots.
    const char* const* hostNames;
    uint32_t hostCount;
    void** hostSlots;
    // For "sub_<address>" rows, the translated function an override can fall back to.
    PPCFunc* const* originals;
    const DataImport* dataImports;
    uint32_t dataImportCount;
    // Function entry counts (control commands countstart/countstop); null when the module
    // was built without TENCHU_ENTRY_COUNTS.
    uint32_t* volatile* entryCounts;
    const char* xexSha256;  // the default.xex the module was translated from
};

using ModuleInitFn = const GameModule* (*)(const RuntimeApi* api);
inline constexpr const char* kModuleInitSymbol = "tenchu_module_init";

// Module side: generated by tools/recompile.py (ppc_module.cpp).
const GameModule* builtinModule();
// Module side: runtime/guest/module_rt.cpp.
uint32_t* volatile* moduleEntryCounts();

}  // namespace tz
